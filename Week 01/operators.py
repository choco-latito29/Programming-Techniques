print("\n****Example 4: Operators*****\n")

# The values of variable1 and variable2 are numeric.
variable1 = 9 # assignment operator
variable2 = 5 # assignment operator

# Comparison operators: The result (True or False) is assigned to a variable.
variable3 = variable1 == variable2 # equal to
variable4 = variable1 >= variable2 # greater than or equal to
variable5 = variable1 > variable2  # greater than
variable6 = variable1 <= variable2 # less than or equal to
variable7 = variable1 < variable2  # less than

print(f"{variable3}") # prints the value of variable3 (False)
print(f"{variable4}") # prints the value of variable4 (True)
print(f"{variable5}") # prints the value of variable5 (True)
print(f"{variable6}") # prints the value of variable6 (False)
print(f"{variable7}") # prints the value of variable7 (False)