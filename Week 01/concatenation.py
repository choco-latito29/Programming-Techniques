print("\n****Example 1: Concatenation*****\n")

# The values of variable1 and variable2 are strings (text), not numbers.
variable1 = '9' # variable1 is a string
variable2 = '5' # variable2 is a string

# The '+' operator concatenates (joins) the two strings.
variable3 = variable1 + variable2

print(f"The result is: {variable3}") # displays 95