# Ejemplo 4: Los valores de variable 1 y variable 2 son numéricos

variable1 = 9 # operador de asignación
variable2 = 5 # operador de asignación

variable3 = variable1 == variable2 # operación de comparación, se asigna a variable c: True o False
variable4 = variable1 >= variable2 # operación mayor o igual que
variable5 = variable1 > variable2 # operación mayor que
variable6 = variable1 <= variable2 # operación menor o igual que
variable7 = variable1 < variable2 # operación menor que

print(f"{variable3}") # imprime el valor de variable 3
print(f"{variable4}") # imprime el valor de variable 4
print(f"{variable5}") # imprime el valor de variable 5
print(f"{variable6}") # imprime el valor de variable 6
print(f"{variable7}") # imprime el valor de variable 7
