# Ejemplo 3: Los valores de variable 1 y variable 2 son numéricos

variable1 = 9 # asignación de valor numérico a variable1
variable2 = 5 # asignación de valor numérico a variable2
variable3 = variable1 + variable2 # operación suma: 14
variable4 = variable1 - variable2 # operación resta: 4
variable5 = variable1 * variable2 # operación multiplicación: 45
variable6 = variable1 / variable2 # operación división: 1.8
variable7 = variable1 ** variable2 # operación potencia: 59049
variable8 = pow(variable1, variable2) # otra forma de la operación potencia: 59049
variable9 = variable1 // variable2 # operación división entera (cociente): 1
variable10 = variable1 % variable2 # operación módulo (residuo): 4
print(f"{variable3}") # muestra el valor de variable3
print(f"{variable4}") # muestra el valor de variable4
print(f"{variable5}") # muestra el valor de variable5
print(f"{variable6}") # muestra el valor de variable6
print(f"{variable7}") # muestra el valor de variable7
print(f"{variable8}") # muestra el valor de variable8
print(f"{variable9}") # muestra el valor de variable9
print(f"{variable10}") # muestra el valor de variable10
