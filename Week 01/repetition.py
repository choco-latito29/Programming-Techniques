# Example 2: Variable 1 is numeric and variable 2 is a string.
variable1 = 9 # Numeric variable
variable2 = '5' # String (character) variable

# The multiplication operator (*) repeats the string.
variable3 = variable1 * variable2

print(f"The result of the multiplication is: {variable3}") # The 9 indicates how many times the '5' will be repeated.