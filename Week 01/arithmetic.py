print("\n****Example 3: Various Arithmetic****\n")

# Example 3: The values of variable1 and variable2 are numeric
variable1 = 9 # assignment of a numeric value to variable1
variable2 = 5 # assignment of a numeric value to variable2

variable3 = variable1 + variable2 # addition operation: 14
variable4 = variable1 - variable2 # subtraction operation: 4
variable5 = variable1 * variable2 # multiplication operation: 45
variable6 = variable1 / variable2 # division operation: 1.8
variable7 = variable1 ** variable2 # power operation: 59049
variable8 = pow(variable1, variable2) # another way for the power operation: 59049
variable9 = variable1 // variable2 # integer division (quotient): 1
variable10 = variable1 % variable2 # modulo operation (remainder): 4

print(f"{variable3}") # displays the value of variable3
print(f"{variable4}") # displays the value of variable4
print(f"{variable5}") # displays the value of variable5
print(f"{variable6}") # displays the value of variable6
print(f"{variable7}") # displays the value of variable7
print(f"{variable8}") # displays the value of variable8
print(f"{variable9}") # displays the value of variable9
print(f"{variable10}") # displays the value of variable10