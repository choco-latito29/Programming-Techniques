# --- File: lists.py ---
# This program demonstrates how to create and use Lists in Python.
# Lists are mutable sequences that can hold different data types.

# Example 1: A list with mixed data types (strings, float, int)
list_example_1 = ["Juan Perez", "Ana", 18.8, 5]

# Example 2: A nested list containing other structures (list, set)
list_example_2 = [1, 3, ["Java", "Python", "SQL"], {"h", "o", "l", "a"}]

# Example 3: A list of strings representing days of the week
list_example_3 = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]

# Printing the entire lists
print(f"List Example 1: {list_example_1}")
print(f"List Example 2: {list_example_2}")

# Accessing a specific element by index
# Index 0 is the first element ("Monday")
print(f"The value at index zero of 'Example 3' is: {list_example_3[0]}")